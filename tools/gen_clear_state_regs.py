#!/usr/bin/env python3
"""src/clear_state_regs.h: the context registers the CLEAR_STATE dump probes.

  python3 tools/gen_clear_state_regs.py CLEARSTATE_CI_H SHADPS4_REGS_CPP

CLEARSTATE_CI_H: drivers/gpu/drm/amd/amdgpu/clearstate_ci.h (Linux, AMD's Sea Islands clear
state). SHADPS4_REGS_CPP: shadPS4's src/video_core/amdgpu/regs.cpp (Regs::SetDefaults()).
Every register of AMD's table (holes left out) with AMD's value and shadPS4's.
"""
import re
import sys


def amd_table(path):
    s = open(path).read()
    arrays = {}
    for m in re.finditer(r"static const unsigned int (ci_SECT_CONTEXT_def_\d+)\[\] =\s*\{(.*?)\};",
                         s, re.S):
        rows = []
        for line in m.group(2).split("\n"):
            r = re.match(r"\s*(0x[0-9a-fA-F]+|0)\s*,\s*//\s*(\S+)", line)
            if r:
                rows.append((int(r.group(1), 16) if r.group(1).startswith("0x") else 0,
                             r.group(2)))
        arrays[m.group(1)] = rows
    regs = []
    for name, base, n in re.findall(
            r"\{\s*(ci_SECT_CONTEXT_def_\d+),\s*(0x[0-9a-fA-F]+),\s*(\d+)\s*\}", s):
        b = int(base, 16) - 0xA000
        for i, (v, reg) in enumerate(arrays[name][:int(n)]):
            if reg != "HOLE":
                regs.append((b + i, v, reg))
    return regs


def shad_defaults(path):
    s = open(path).read()
    vals = {}
    i = s.index("REG_ARRAY_DEFAULT = {")
    arr = s[i:s.index("};", i)]
    for k, v in enumerate(re.findall(r"0x([0-9a-fA-F]+)u", arr)):
        vals[0x80 + k] = int(v, 16)
    body = s[s.index("void Regs::SetDefaults()"):]
    for off, v in re.findall(r"ContextRegWordOffset \+ 0x([0-9a-fA-F]+)\]\s*=\s*0x([0-9a-fA-F]+)u",
                             body):
        vals[int(off, 16)] = int(v, 16)
    return vals


def main():
    regs = amd_table(sys.argv[1])
    shad = shad_defaults(sys.argv[2])
    out = ["/* Generated by tools/gen_clear_state_regs.py: the context registers of AMD's Sea "
           "Islands",
           "   clear state (Linux amdgpu clearstate_ci.h) with AMD's value and shadPS4's "
           "Regs::SetDefaults(). */",
           "#pragma once", "#include <stdint.h>", "",
           "static const struct {", "    uint16_t idx;", "    uint32_t amd, shad;",
           "    const char* name;", "} k_clear_state_regs[] = {"]
    for idx, v, name in regs:
        out.append('    {0x%03X, 0x%08Xu, 0x%08Xu, "%s"},' % (idx, v, shad.get(idx, 0), name))
    out += ["};",
            "#define CLEAR_STATE_NREGS ((int)(sizeof(k_clear_state_regs) / "
            "sizeof(k_clear_state_regs[0])))", ""]
    open("src/clear_state_regs.h", "w").write("\n".join(out))
    print(len(regs), "registers")


if __name__ == "__main__":
    main()
